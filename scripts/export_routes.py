#!/usr/bin/env python3
"""Export Flask routes as a generated manifest and check ARCHITECTURE.json."""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

IGNORED = {"HEAD", "OPTIONS"}


def collect(app) -> list[dict]:
    rows = []
    for rule in app.url_map.iter_rules():
        if rule.endpoint == "static":
            continue
        methods = sorted(rule.methods - IGNORED)
        for method in methods:
            rows.append(
                {
                    "rule": rule.rule,
                    "method": method,
                    "endpoint": rule.endpoint,
                    "blueprint": rule.endpoint.split(".")[0],
                }
            )
    return sorted(rows, key=lambda item: (item["rule"], item["method"]))


def _enabled(flag: str) -> bool:
    return os.environ.get(flag, "").strip().lower() in {"1", "true", "yes", "on"}


def _optional_disabled(endpoint: dict) -> bool:
    flag = endpoint.get("feature_flag")
    optional = endpoint.get("optional")
    if not flag and isinstance(optional, str):
        flag = optional
    if endpoint.get("optional") is True and not flag:
        return True
    return bool(flag) and not _enabled(flag)


def json_keys(arch: dict) -> set[tuple[str, str]]:
    keys = set()
    for endpoint in arch.get("api", {}).get("endpoints", []):
        if endpoint.get("status") == "planned":
            continue
        if _optional_disabled(endpoint):
            continue
        for method in endpoint.get("methods") or ["GET"]:
            method = method.upper()
            if method not in IGNORED:
                keys.add((endpoint.get("rule", ""), method))
    return keys


def app_keys(rows: list[dict]) -> set[tuple[str, str]]:
    return {(row["rule"], row["method"]) for row in rows}


def write_manifest(rows: list[dict], out: Path) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        json.dumps({"generated_from": "Flask url_map", "count": len(rows), "routes": rows},
                   ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    md = out.with_suffix(".md")
    by_blueprint: dict[str, list[dict]] = {}
    for row in rows:
        by_blueprint.setdefault(row["blueprint"], []).append(row)
    lines = [
        "# Generated Route Manifest",
        "",
        "> Generated by `scripts/export_routes.py --write`; do not edit.",
        f"> route+method: {len(rows)}",
        "",
    ]
    for blueprint in sorted(by_blueprint):
        lines += [f"## {blueprint}", "", "| Method | Rule | Endpoint |", "|---|---|---|"]
        for row in by_blueprint[blueprint]:
            lines.append(f"| {row['method']} | `{row['rule']}` | `{row['endpoint']}` |")
        lines.append("")
    md.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--arch", default=str(ROOT / "ARCHITECTURE.json"))
    parser.add_argument("--out", default=str(ROOT / "docs/architecture/generated/routes.json"))
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    import api_server  # noqa: E402

    rows = collect(api_server.app)
    if args.write:
        write_manifest(rows, Path(args.out))
        print(f"wrote {args.out} ({len(rows)} route+method)")
    arch = json.loads(Path(args.arch).read_text(encoding="utf-8"))
    expected = json_keys(arch)
    actual = app_keys(rows)
    missing = sorted(expected - actual)
    wild = sorted(actual - expected)
    if missing:
        print("MISSING_IN_FLASK")
        for rule, method in missing:
            print(f"  {method} {rule}")
    if wild:
        print("NOT_IN_ARCHITECTURE")
        for rule, method in wild:
            print(f"  {method} {rule}")
    print(f"json_routes={len(expected)} app_routes={len(actual)}")
    ok = not missing and not wild
    if args.check and not ok:
        return 1
    print("OK" if ok else "DRIFT")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
